void mosaic_i18n_set_language(mosaic_ui_language_t language)
{
    if (language < MOSAIC_UI_LANGUAGE_EN || language > MOSAIC_UI_LANGUAGE_ZH_CN) {
        language = MOSAIC_UI_LANGUAGE_EN;
    }
    atomic_store(&s_language, language);
}

mosaic_ui_language_t mosaic_i18n_get_language(void)
{
    return (mosaic_ui_language_t)atomic_load(&s_language);
}

const char *mosaic_i18n_text(const char *english)
{
    if (english == NULL || mosaic_i18n_get_language() != MOSAIC_UI_LANGUAGE_ZH_CN) {
        return english;
    }
    for (size_t i = 0; i < sizeof(s_zh_cn) / sizeof(s_zh_cn[0]); ++i) {
        if (strcmp(english, s_zh_cn[i].english) == 0) {
            return s_zh_cn[i].chinese;
        }
    }
    return english;
}

esp_err_t mosaic_i18n_apply_components(esp_gsp_handle_t ui, const mosaic_i18n_component_t *components, size_t count)
{
    if (ui == NULL || (components == NULL && count != 0)) return ESP_ERR_INVALID_ARG;
    if (mosaic_i18n_get_language() != MOSAIC_UI_LANGUAGE_ZH_CN) return ESP_OK;
    if (count > ESP_GSP_BUILD_CAP_TRANSACTION_UPDATE_CAPACITY) return ESP_ERR_INVALID_SIZE;
    esp_gsp_update_command_t updates[ESP_GSP_BUILD_CAP_TRANSACTION_UPDATE_CAPACITY];
    size_t update_count = 0;
    for (size_t i = 0; i < count; ++i) {
        const char *translated = mosaic_i18n_text(components[i].english);
        if (translated == components[i].english) continue;
        updates[update_count++] = (esp_gsp_update_command_t) {
            .kind = ESP_GSP_UPDATE_TEXT,
            .bind = components[i].bind,
            .text = translated,
        };
    }
    if (update_count == 0) return ESP_OK;
    esp_gsp_update_receipt_t *receipt = NULL;
    const esp_gsp_err_t err = esp_gsp_update_submit(ui, updates, update_count, NULL, &receipt);
    if (receipt != NULL) esp_gsp_update_release(receipt);
    return err == ESP_GSP_OK ? ESP_OK : (esp_err_t)err;
}
